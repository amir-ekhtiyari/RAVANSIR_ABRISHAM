"""
Builds templates/partials/route_map_geo.html: a real map (Mercator, Europe → Middle East) with the
company's routes. Country shapes: github.com/johan/world.geo.json (public domain, UNLICENSE).

    python tools/build_route_map.py path/to/countries.geo.json
"""

import json
import math
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / 'templates' / 'partials' / 'route_map_geo.html'
W, H = 1000, 640
LON0, LON1, LAT0, LAT1 = -4.0, 63.0, 26.0, 56.5
HIGHLIGHT = {'IRN': 'hub', 'TUR': 'on', 'IRQ': 'on', 'AZE': 'on'}
EUROPE = {'DEU', 'FRA', 'ITA', 'AUT', 'CZE', 'POL', 'HUN', 'SVK', 'SVN', 'HRV', 'BIH', 'SRB', 'MNE', 'MKD', 'ALB',
          'GRC', 'BGR', 'ROU', 'NLD', 'BEL', 'LUX', 'CHE', 'DNK', 'ESP', 'PRT', 'GBR', 'IRL', 'SWE', 'NOR', 'FIN',
          'EST', 'LVA', 'LTU', 'MDA', 'UKR', 'BLR', 'CYP', 'KOS'}


def merc_y(lat):
    return math.log(math.tan(math.pi / 4 + math.radians(lat) / 2))


Y0, Y1 = merc_y(LAT0), merc_y(LAT1)


def proj(lon, lat):
    x = (lon - LON0) / (LON1 - LON0) * W
    y = (Y1 - merc_y(lat)) / (Y1 - Y0) * H
    return x, y


def ring_path(ring):
    pts = [proj(lon, lat) for lon, lat in ring]
    out, last = [], None
    for x, y in pts:
        p = (round(x, 1), round(y, 1))
        if p != last:
            out.append(p)
            last = p
    if len(out) < 3:
        return ''
    return 'M' + 'L'.join(f'{x} {y}' for x, y in out) + 'Z'


def visible(geom):
    polys = geom['coordinates'] if geom['type'] == 'MultiPolygon' else [geom['coordinates']]
    for poly in polys:
        for lon, lat in poly[0]:
            if LON0 - 8 < lon < LON1 + 8 and LAT0 - 8 < lat < LAT1 + 8:
                return True
    return False


def country_path(geom):
    polys = geom['coordinates'] if geom['type'] == 'MultiPolygon' else [geom['coordinates']]
    return ''.join(ring_path(r) for poly in polys for r in poly[:1])


CITIES = {  # lon, lat
    'IR': (51.39, 35.69), 'TR': (28.98, 41.01), 'EU': (11.58, 48.14), 'IQ': (44.37, 33.31), 'AZ': (49.87, 40.41),
}
BORDERS = {'bazargan': (44.39, 39.39), 'razi': (44.05, 38.62), 'serow': (44.57, 37.73), 'jolfa': (45.60, 38.94)}
ROUTES = [('tr-ir', 'TR', 'IR', -60), ('ir-tr', 'IR', 'TR', -40), ('ir-eu', 'IR', 'EU', -150), ('ir-iq', 'IR', 'IQ', 40),
          ('ir-az', 'IR', 'AZ', -30)]


def arc(a, b, bend):
    (x1, y1), (x2, y2) = proj(*CITIES[a]), proj(*CITIES[b])
    mx, my = (x1 + x2) / 2, (y1 + y2) / 2
    dx, dy = x2 - x1, y2 - y1
    length = math.hypot(dx, dy) or 1
    nx, ny = -dy / length, dx / length
    if a != 'IR':                      # keep each outbound/inbound pair on opposite sides
        bend = -bend
    cx, cy = mx + nx * bend, my + ny * bend
    return f'M{x1:.1f} {y1:.1f} Q{cx:.1f} {cy:.1f} {x2:.1f} {y2:.1f}'


def main(src):
    data = json.loads(Path(src).read_text(encoding='utf-8'))
    land, hi = [], []
    for f in data['features']:
        if not visible(f['geometry']):
            continue
        d = country_path(f['geometry'])
        cls = HIGHLIGHT.get(f['id'])
        if cls:
            hi.append(f'<path class="rm-land rm-land--{cls}" d="{d}"/>')
        else:
            extra = ' rm-land--eu' if f['id'] in EUROPE else ''
            land.append(f'<path class="rm-land{extra}" d="{d}"/>')
    paths = ''.join(f'<path id="rt-{k}" d="{arc(a, b, bend)}"/>' for k, a, b, bend in ROUTES)
    cities = {k: tuple(round(v, 1) for v in proj(*ll)) for k, ll in CITIES.items()}
    borders = {k: tuple(round(v, 1) for v in proj(*ll)) for k, ll in BORDERS.items()}
    tpl = TEMPLATE
    for k, (x, y) in {**cities, **borders}.items():
        tpl = tpl.replace(f'@{k}Xp', f'{x / W * 100:.2f}%').replace(f'@{k}Yp', f'{y / H * 100:.2f}%')
        tpl = tpl.replace(f'@{k}X', str(x)).replace(f'@{k}Y', str(y))
    tpl = tpl.replace('@LAND', ''.join(land)).replace('@HILAND', ''.join(hi)).replace('@PATHS', paths)
    OUT.write_text(tpl, encoding='utf-8')
    print('written', OUT, len(tpl) // 1024, 'KB')


